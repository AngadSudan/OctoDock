const generateSlug = () => {
  let word = "";
  for (let i = 0; i < 3; i++) {
    word += slugWords[Math.floor(Math.random() * 100)];
    if (i !== 2) {
      word += "-";
    }
  }
  return word;
};

export default generateSlug;
